def gen_species(repo, consts, dex, display, out):
    names = read_name_table(cparse.repo_path(repo, "src/data/text/species_names.h"), "gSpeciesNames")
    info = read_struct_table(cparse.repo_path(repo, "src/data/pokemon/species_info.h"), "gSpeciesInfo")
    ability_names = read_name_table(cparse.repo_path(repo, "src/data/text/abilities.h"), "gAbilityNames")

    # species internal id -> national number, in the order of sSpeciesToNationalPokedexNum
    nat_src = cparse.repo_path(repo, "src/pokemon.c")
    order = read_flat_list(nat_src, "sSpeciesToNationalPokedexNum[NUM_SPECIES - 1]")
    internal_to_national = {}
    for entry in order:
        m = re.fullmatch(r"SPECIES_TO_NATIONAL\((\w+)\)", entry)
        if not m:
            raise SystemExit(f"unexpected sSpeciesToNationalPokedexNum entry: {entry!r}")
        internal = consts[f"SPECIES_{m.group(1)}"]
        internal_to_national[internal] = dex[f"NATIONAL_DEX_{m.group(1)}"]

    rows = []
    for internal in sorted(internal_to_national):
        const = f"SPECIES_{_species_suffix(consts, internal)}"
        rec = info.get(const)
        if rec is None or not rec:
            continue
        base = [_int(consts, rec[k]) for k in ("baseHP", "baseAttack", "baseDefense",
                                               "baseSpeed", "baseSpAttack", "baseSpDefense")]
        types = [_int(consts, t) for t in _braced_list(rec["types"])]
        tnames = "/".join(dict.fromkeys(TYPE_NAMES[t] for t in types))
        gender = _gender_ratio(consts, rec["genderRatio"])
        growth = GROWTH_CODES[rec["growthRate"]]
        abil = [_int(consts, a) for a in _braced_list(rec["abilities"])]
        abil_names = []
        for a in abil:
            const_a = _ability_suffix(consts, a)
            abil_names.append("(none)" if a == consts["ABILITY_NONE"]
                              else display.name("abilities", const_a, ability_names[const_a]))
        if abil_names[1] in ("(none)", abil_names[0]):
            abil_names[1] = abil_names[0]
        rows.append([internal, internal_to_national[internal],
                     display.name("species", const, names[const]),
                     ",".join(str(b) for b in base), tnames, gender, growth, "/".join(abil_names)])
    out["species"] = write_table("species.txt", [
        "internal id|national dex|name|base hp,atk,def,spe,spa,spd|types|gender ratio|growth|ability1/ability2",
        "Sources: constants/species.h, constants/pokedex.h, src/pokemon.c (sSpeciesToNationalPokedexNum),",
        "         src/data/pokemon/species_info.h, src/data/text/species_names.h, src/data/text/abilities.h",
        "Gender ratio: 0 = always male, 254 = always female, 255 = genderless, else female threshold.",
        "Base stats are in the save's internal order (HP, Atk, Def, Spe, SpA, SpD)."], rows)
    return internal_to_national


def _species_suffix(consts, value):
    best = None
    for k, v in consts.items():
        if not k.startswith("SPECIES_") or v != value or k in ("SPECIES_NONE",):
            continue
        if best is None or (best.startswith("SPECIES_OLD_UNOWN") and not k.startswith("SPECIES_OLD_UNOWN")):
            best = k
    if best is None:
        raise SystemExit(f"no SPECIES_* constant has value {value}")
    return best[len("SPECIES_"):]


def _ability_suffix(consts, value):
    for k, v in consts.items():
        if k.startswith("ABILITY_") and v == value and k != "ABILITIES_COUNT":
            return k
    raise SystemExit(f"no ABILITY_* constant has value {value}")


def _gender_ratio(consts, expr):
    m = re.fullmatch(r"PERCENT_FEMALE\(([\d.]+)\)", expr.strip())
    if m:
        return min(254, int(float(m.group(1)) * 255) // 100)
    return _int(consts, expr)


def gen_moves(repo, consts, display, out):
    names = read_name_table(cparse.repo_path(repo, "src/data/text/move_names.h"), "gMoveNames")
    moves = read_struct_table(cparse.repo_path(repo, "src/data/battle_moves.h"), "gBattleMoves")
    rows = []
    for const, fields in moves.items():
        mid = consts[const]
        if mid == 0:
            continue
        rows.append([mid, display.name("moves", const, names[const]), _int(consts, fields["pp"])])
    rows.sort(key=lambda r: r[0])
    out["moves"] = write_table("moves.txt", [
        "move id|name|base PP",
        "Sources: constants/moves.h, src/data/battle_moves.h, src/data/text/move_names.h"], rows)


def gen_items(repo, consts, display, out):
    with open(cparse.repo_path(repo, "src/data/items.json"), encoding="utf-8") as f:
        items = json.load(f)["items"]
    tm_moves = read_flat_list(cparse.repo_path(repo, "src/data/party_menu.h"), "sTMHMMoves[TMHM_COUNT]")
    move_names = read_name_table(cparse.repo_path(repo, "src/data/text/move_names.h"), "gMoveNames")
    rows, tm_rows = [], []
    for item_id, it in enumerate(items):
        const = it["itemId"]
        if item_id and const == "ITEM_NONE":
            continue   # two unused slots between the HMs and the Kanto key items
        if const != "ITEM_NONE" and consts[const] != item_id:
            raise SystemExit(f"items.json index {item_id} is {const} but constants say {consts[const]}")
        name = display.name("items", const, it["english"])
        pocket = it["pocket"].replace("POCKET_", "").lower()
        rows.append([item_id, name, pocket])
    for tm_index, move_const in enumerate(tm_moves):
        item_id = consts["ITEM_TM01"] + tm_index
        tm_rows.append([tm_index, item_id, consts[move_const],
                        display.name("moves", move_const, move_names[move_const])])
    out["items"] = write_table("items.txt", [
        "item id|name|pocket",
        "Sources: src/data/items.json, constants/items.h",
        f"ITEMS_COUNT = {consts['ITEMS_COUNT']}. Pockets: items, medicine, key_items, held_items,",
        "poke_balls, tm_case, berry_pouch."], rows)
    out["tmhm"] = write_table("tmhm.txt", [
        "tm/hm index (0-based)|item id|move id|move name",
        "Sources: src/data/party_menu.h (sTMHMMoves), constants/items.h",
        "Index i is the bit position in SaveBlock1.bagPocket_TMHM and item ITEM_TM01 + i."], tm_rows)


def gen_mapsec(repo, consts, display, out):
    with open(cparse.repo_path(repo, "src/data/region_map/region_map_sections.json"), encoding="utf-8") as f:
        sections = json.load(f)["map_sections"]
    rows = []
    for sec in sections:
        const = sec["map_section"]
        rows.append([consts[const], display.name("mapsec", const, sec["name"])])
    rows.sort(key=lambda r: r[0])
    for value, label in [(consts["MAPSEC_NONE"], "(none)"),
                         (consts["METLOC_SPECIAL_EGG"], "Egg (special)"),
                         (consts["METLOC_IN_GAME_TRADE"], "In-game trade"),
                         (consts["METLOC_FATEFUL_ENCOUNTER"], "Fateful encounter (event)")]:
        if not any(r[0] == value for r in rows):
            rows.append([value, label])
    out["mapsec"] = write_table("mapsec.txt", [
        "map section id|name  (this is what a Pokémon's met location stores)",
        "Sources: constants/region_map_sections.h, src/data/region_map/region_map_sections.json"], rows)


MAP_LABEL_WORDS = {"SSANNE": "S.S. Anne", "SS": "S.S.", "POKEMON": "Pokémon", "MT": "Mt.",
                   "PC": "PC", "TV": "TV", "HQ": "HQ", "OF": "of", "AND": "and", "THE": "the",
                   "DIGLETTS": "Diglett's", "SEAGALLOP": "Seagallop", "NPC": "NPC"}
# Floor/room markers that must keep their original casing.
MAP_LABEL_KEEP = re.compile(r"B?\d+F|\d+[A-Z]?|[A-Z]\d+|ROOF|PH")


def map_label(const):
    """MAP_FUCHSIA_CITY_POKEMON_CENTER_1F -> 'Fuchsia City Pokémon Center 1F'."""
    words = []
    for w in const[len("MAP_"):].split("_"):
        if w in MAP_LABEL_WORDS:
            words.append(MAP_LABEL_WORDS[w])
        elif MAP_LABEL_KEEP.fullmatch(w):
            words.append(w)
        else:
            # ROUTE23 -> "Route 23", but leave 1F/B2F style markers alone
            m = re.fullmatch(r"([A-Z]{3,})(\d+)", w)
            if m:
                words.append(titlecase(m.group(1)))
                words.append(m.group(2))
            else:
                words.append(titlecase(w))
    return " ".join(words)


def gen_maps(repo, consts, out):
    maps_dir = cparse.repo_path(repo, "data/maps")
    by_const = {}
    for folder in sorted(os.listdir(maps_dir)):
        path = os.path.join(maps_dir, folder, "map.json")
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as f:
            m = json.load(f)
        by_const[m["id"]] = (m.get("region_map_section", "MAPSEC_NONE"), m["name"])
    rows = []
    for const, (mapsec, folder) in by_const.items():
        if const not in consts:
            continue
        value = consts[const]
        rows.append([f"{value >> 8}.{value & 0xFF}", const[len("MAP_"):],
                     consts.get(mapsec, consts["MAPSEC_NONE"]), folder, map_label(const)])
    rows.sort(key=lambda r: (int(r[0].split(".")[0]), int(r[0].split(".")[1])))
    out["maps"] = write_table("maps.txt", [
        "group.number|map constant (without MAP_)|map section id|folder name in data/maps|readable name",
        "Sources: constants/map_groups.h, data/maps/*/map.json",
        "SaveBlock1.location stores mapGroup then mapNum, which is this group.number."], rows)


def gen_flags(repo, consts, out):
    rows = []
    for name, value in sorted(consts.items(), key=lambda kv: kv[1]):
        if not name.startswith("FLAG_") or name in ("FLAGS_COUNT",):
            continue
        if re.fullmatch(r"FLAG_0x[0-9A-Fa-f]+", name):
            continue       # unnamed placeholder flags carry no information
        if not 0 <= value < consts["FLAGS_COUNT"]:
            continue
        rows.append([f"0x{value:03X}", name])
    seen, uniq = set(), []
    for value, name in rows:
        if value in seen:
            continue
        seen.add(value)
        uniq.append([value, name])
    out["flags"] = write_table("flags.txt", [
        "flag id (hex)|constant name",
        "Source: constants/flags.h. Placeholder FLAG_0x... names are left out.",
        f"FLAGS_COUNT = 0x{consts['FLAGS_COUNT']:X}; trainer-defeated flags are "
        f"0x{consts['TRAINER_FLAGS_START']:03X}-0x{consts['TRAINER_FLAGS_END']:03X}; "
        f"system flags start at 0x{consts['SYS_FLAGS']:03X}."], uniq)


def gen_vars(repo, consts, out):
    rows = []
    for name, value in sorted(consts.items(), key=lambda kv: kv[1]):
        if not name.startswith("VAR_") or re.fullmatch(r"VAR_0x[0-9A-Fa-f]+", name):
            continue
        if not consts["VARS_START"] <= value <= consts["VARS_END"]:
            continue
        rows.append([f"0x{value:04X}", name])
    out["vars"] = write_table("vars.txt", [
        "var id (hex)|constant name",
        "Source: constants/vars.h. Placeholder VAR_0x... names are left out.",
        f"SaveBlock1.vars covers 0x{consts['VARS_START']:04X}-0x{consts['VARS_END']:04X}."], rows)


