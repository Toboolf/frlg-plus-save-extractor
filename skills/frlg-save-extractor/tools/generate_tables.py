# ---------------------------------------------------------------- display names
def titlecase(s):
    """ALL-CAPS game text -> Title Case, leaving apostrophes and symbols alone."""
    out, boundary = [], True
    for ch in s:
        if ch.isalpha():
            out.append(ch.upper() if boundary else ch.lower())
            boundary = False
        else:
            out.append(ch)
            boundary = ch != "'"
    return "".join(out)


def _normalise(s):
    return re.sub(r"[^0-9a-z♀♂]", "", s.lower()).replace("é", "e")


class Display:
    """Applies tools/display_names.json, refusing any override that renames."""

    def __init__(self, path):
        with open(path, encoding="utf-8") as f:
            self.tables = json.load(f)
        self.used = set()

    def name(self, group, const, game_name):
        override = self.tables.get(group, {}).get(const)
        if override is None:
            if re.fullmatch(r"(TM|HM)\d\d", game_name):
                return game_name
            return titlecase(game_name)
        self.used.add((group, const))
        if _normalise(override) != _normalise(game_name):
            raise SystemExit(f"display_names.json: {group}/{const} says {override!r} but the repo "
                             f"calls it {game_name!r} — overrides may only change capitalisation.")
        return override

    def unused(self):
        return [f"{g}/{k}" for g, t in self.tables.items() if isinstance(t, dict)
                for k in t if (g, k) not in self.used]


# ---------------------------------------------------------------- writing
def write_table(name, header, rows):
    path = os.path.join(OUT_DIR, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write("# Generated by tools/generate_tables.py — do not edit by hand.\n")
        for line in header:
            f.write(f"# {line}\n")
        for row in rows:
            f.write("|".join(str(c) for c in row) + "\n")
    print(f"  {name}: {len(rows)} rows")
    return len(rows)


