def gen_evolutions(repo, consts, out):
    path = cparse.repo_path(repo, "src/data/pokemon/evolution.h")
    with open(path, encoding="utf-8") as f:
        text = cparse._strip_block_comments(f.read())
    start = text.index("gEvolutionTable")
    body = text[text.index("{", start):]
    rows = []
    for m in re.finditer(r"\[\s*(SPECIES_\w+)\s*\]\s*=\s*\{(.*?)\}\s*,\s*\n", body, re.S):
        frm = consts[m.group(1)]
        for evo in re.finditer(r"\{([^{}]*)\}", m.group(2)):
            parts = [p.strip() for p in evo.group(1).split(",")]
            if len(parts) < 3 or parts[0] in ("0", ""):
                continue
            method, param, target = parts[0], parts[1], parts[2]
            rows.append([frm, method[len("EVO_"):].lower(), _int(consts, param), consts[target]])
    rows.sort(key=lambda r: (r[0], r[3]))
    out["evolutions"] = write_table("evolutions.txt", [
        "from species (internal)|method|parameter|into species (internal)",
        "Source: src/data/pokemon/evolution.h",
        "method 'level' means the parameter is the level; 'item' means it is an item id."], rows)


